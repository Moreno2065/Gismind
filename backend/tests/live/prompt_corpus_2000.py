@dataclass(frozen=True)
class Case:
    case_id: str
    family: str
    kind: str
    profile: int
    paraphrase: int
    prompt: str
    file_format: str

    @property
    def count(self):
        return self.profile + 4

    @property
    def distance(self):
        return 25 * (self.profile + 1)

    @property
    def threshold(self):
        return 10 * (self.profile + 1)

    @property
    def factor(self):
        return self.profile + 2

def load_cases():
    result = []
    for family, phrases in PHRASES.items():
        for profile in range(10):
            kind = 'negative' if family in ('broken_vector', 'bad_csv') else 'ambiguity' if family.startswith('missing_') else 'success'
            fmt = 'csv' if family in ('csvpoints', 'bad_csv') else 'tif' if family == 'rastercalc' else 'geojson' if family == 'broken_vector' else ('geojson', 'zip', 'gpkg')[profile % 3]
            label = {'geojson': '地理杰森文件', 'zip': '形状文件压缩包', 'gpkg': '地理包文件', 'csv': '逗号分隔表', 'tif': '带地理参考的栅格'}[fmt]
            n = profile + 4
            if family == 'broken_vector':
                context = f'附件是第{n}条记录处中断的{label}。'
            elif family == 'bad_csv':
                context = f'附件是{n}行的{label}，异常纬度为{100 + profile}度。'
            elif family == 'rastercalc':
                context = f'附件为{n}行{n}列的{label}，网页墨卡托投影，单位米。'
            elif family == 'csvpoints':
                context = f'附件是含{n}行点位的{label}，坐标列名是经度、纬度。'
            else:
                geometry = '点' if family in ('buffer', 'hull', 'dedup', 'missing_distance') else '面'
                context = f'附件为{label}，每份含{n}个{geometry}要素，坐标采用网页墨卡托投影，单位米。'
                if family == 'dedup':
                    context = f'附件为{label}，含{n}个不同位置，每个点重复两次；网页墨卡托投影，单位米。'
                if family == 'explode':
                    context = f'附件为{label}，含{n}个双部件面；网页墨卡托投影，单位米。'
            for paraphrase, text in enumerate(phrases):
                prompt = context + text.format(distance=25 * (profile + 1), threshold=10 * (profile + 1), factor=profile + 2)
                result.append(Case(f'zh-{family}-{profile:02d}-{paraphrase:02d}', family, kind, profile, paraphrase, prompt, fmt))
    return tuple(result)

def corpus_digest(cases):
    raw = '\n'.join(json.dumps(asdict(c), ensure_ascii=False, sort_keys=True, separators=(',', ':')) for c in cases)
    return hashlib.sha256(raw.encode('utf-8')).hexdigest()

